// Multi-language (i18n) Engine for CalMal
// Supports English (en, default) & Bahasa Melayu (ms)
import { store } from '../services/store.js';

const STORAGE_KEY = 'calmal_lang';
const listeners = new Set();

let currentLang = (() => {
  try {
    const saved = localStorage.getItem(STORAGE_KEY);
    if (saved === 'ms' || saved === 'en') return saved;
    return store.settings?.lang === 'ms' ? 'ms' : 'en';
  } catch {
    return 'en';
  }
})();

export function getLang() {
  return currentLang;
}

export function setLang(lang) {
  if (lang !== 'en' && lang !== 'ms') return;
  currentLang = lang;
  try {
    localStorage.setItem(STORAGE_KEY, lang);
    store.saveSettings({ lang });
    document.documentElement.lang = lang;
  } catch {
    /* noop */
  }
  listeners.forEach((fn) => fn(currentLang));
}

export function toggleLang() {
  setLang(currentLang === 'en' ? 'ms' : 'en');
  return currentLang;
}

export function onLangChange(fn) {
  listeners.add(fn);
  return () => listeners.delete(fn);
}

